#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const registry = JSON.parse(fs.readFileSync(path.join(root, "src/data/phenome-registry.json"), "utf8"));
const pageData = JSON.parse(fs.readFileSync(path.join(root, "src/data/therapeutic-area-pages.json"), "utf8"));
const outDir = path.join(root, "docs/therapeutic-areas");

for (const profile of pageData.pages) {
  const ta = registry.therapeuticAreas.find((entry) => entry.id === profile.taId);
  if (!ta) throw new Error(`Unknown therapeutic area ${profile.taId}`);
  const body = `---
id: ${ta.slug}
title: ${JSON.stringify(ta.name)}
sidebar_label: ${JSON.stringify(ta.name)}
description: ${JSON.stringify(ta.description)}
tags:
  - Therapeutic Area
hide_title: true
---

{/* Generated by scripts/generate-therapeutic-area-pages.mjs. */}
<TherapeuticAreaDetail taId="${ta.id}" />
`;
  const target = path.join(outDir, `${ta.slug}.mdx`);
  fs.writeFileSync(target, body);
  console.log(`wrote ${path.relative(root, target)}`);
}
